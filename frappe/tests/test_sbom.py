from importlib.metadata import version

from spdx_tools.spdx.parser.jsonlikedict.json_like_dict_parser import JsonLikeDictParser
from spdx_tools.spdx.validation.document_validator import validate_full_spdx_document

from frappe.tests import UnitTestCase
from frappe.utils.sbom.collector import License, _npm_alias_target, _yarn_source, collect, parse_yarn_lock
from frappe.utils.sbom.licenses import NOASSERTION, to_spdx_license
from frappe.utils.sbom.spdx import to_spdx

YARN_LOCK = """\
# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@scope/a@^1.0.0", "@scope/a@^1.2.0":
  version "1.2.3"
  resolved "https://registry.yarnpkg.com/@scope/a/-/a-1.2.3.tgz#0123456789abcdef0123456789abcdef01234567"
  dependencies:
    b "^2.0.0"
  optionalDependencies:
    "@scope/c" ">=1 <2"

b@^2.0.0:
  version "2.0.1"
  resolved "https://registry.yarnpkg.com/b/-/b-2.0.1.tgz"
  integrity sha512-AAAA
"""


class TestYarnLock(UnitTestCase):
	def test_parse(self):
		entries = parse_yarn_lock(YARN_LOCK)

		self.assertIs(entries["@scope/a@^1.0.0"], entries["@scope/a@^1.2.0"])
		self.assertEqual(entries["@scope/a@^1.0.0"]["version"], "1.2.3")
		self.assertEqual(entries["@scope/a@^1.0.0"]["dependencies"], {"b": "^2.0.0"})
		self.assertEqual(entries["@scope/a@^1.0.0"]["optionalDependencies"], {"@scope/c": ">=1 <2"})
		self.assertEqual(entries["b@^2.0.0"]["integrity"], "sha512-AAAA")
		self.assertEqual(parse_yarn_lock('__metadata:\n  version: 6\n"b@npm:^2":\n'), {})

	def test_source(self):
		entries = parse_yarn_lock(YARN_LOCK)

		self.assertEqual(
			_yarn_source(entries["@scope/a@^1.0.0"]),
			("https://registry.yarnpkg.com/@scope/a/-/a-1.2.3.tgz", "sha1-ASNFZ4mrze8BI0VniavN7wEjRWc="),
		)
		self.assertEqual(
			_yarn_source(entries["b@^2.0.0"]), ("https://registry.yarnpkg.com/b/-/b-2.0.1.tgz", "sha512-AAAA")
		)

	def test_alias(self):
		self.assertEqual(_npm_alias_target("string-width-cjs", "npm:string-width@^4.2.0"), "string-width")
		self.assertEqual(_npm_alias_target("x", "npm:@scope/y@^1"), "@scope/y")
		self.assertEqual(_npm_alias_target("x", "^1"), "x")


class TestLicenses(UnitTestCase):
	def test_to_spdx(self):
		self.assertEqual(
			to_spdx_license(License(expression="mit OR apache-2.0")), ("MIT OR Apache-2.0", None)
		)
		self.assertEqual(to_spdx_license(License(text="BSD-3-Clause")), ("BSD-3-Clause", None))
		self.assertEqual(
			to_spdx_license(License(classifiers=("License :: OSI Approved :: MIT License",))), ("MIT", None)
		)
		self.assertEqual(
			to_spdx_license(License(classifiers=("License :: OSI Approved :: BSD License",))),
			(NOASSERTION, "License :: OSI Approved :: BSD License"),
		)
		self.assertEqual(
			to_spdx_license(License(expression="SEE LICENSE IN LICENSE.md")),
			(NOASSERTION, "SEE LICENSE IN LICENSE.md"),
		)
		self.assertEqual(to_spdx_license(License()), (NOASSERTION, None))


class TestSPDX(UnitTestCase):
	@classmethod
	def setUpClass(cls):
		super().setUpClass()
		cls.document = to_spdx(collect(["frappe"]), "example.com")
		cls.ids = {p["SPDXID"]: p for p in cls.document["packages"]}

	def get_package_id(self, purl: str) -> str:
		for package in self.document["packages"]:
			if any(ref["referenceLocator"] == purl for ref in package.get("externalRefs", [])):
				return package["SPDXID"]
		self.fail(f"{purl} is not in the SBOM")

	def test_document_is_valid(self):
		messages = validate_full_spdx_document(JsonLikeDictParser().parse(self.document))
		self.assertEqual([m.validation_message for m in messages], [])

	def test_describes_frappe(self):
		described = [
			self.ids[r["relatedSpdxElement"]]["name"]
			for r in self.document["relationships"]
			if r["spdxElementId"] == "SPDXRef-DOCUMENT" and r["relationshipType"] == "DESCRIBES"
		]
		self.assertEqual(described, ["frappe"])

	def test_frappe_depends_on_werkzeug(self):
		frappe_id = next(
			p["SPDXID"] for p in self.document["packages"] if p["primaryPackagePurpose"] == "APPLICATION"
		)
		werkzeug = self.get_package_id(f"pkg:pypi/werkzeug@{version('werkzeug')}")
		self.assertIn(
			{
				"spdxElementId": frappe_id,
				"relationshipType": "DEPENDS_ON",
				"relatedSpdxElement": werkzeug,
			},
			self.document["relationships"],
		)
